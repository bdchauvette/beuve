import { revealFormatControls } from '#x/text/reveal-format-controls.ts';

import { escapeMarkdownHtml } from './escape-markdown-html.ts';
import { fenceCodeBlock } from './fence-code-block.ts';
import { formatUraAnchor } from './format-ura-anchor.ts';
import { parseSuggestedPatch } from './parse-suggested-patch.ts';
import { uraSeverityEmoji } from './ura-severity-emoji.ts';
import type {
  OutdatedReason,
  UraArtifact,
  UraEntry,
  UraPlacedSuggestion,
  UraVerdict,
} from './ura-artifact.ts';
import type { PatchHunk, UraAnchor, UraItem, UraOrigin } from './ura-item.ts';

/** One inline comment of a review; `start_*` are present only for multi-line ranges. */
export type GithubReviewComment = {
  readonly path: string;
  readonly line: number;
  readonly side: 'RIGHT';
  readonly body: string;
} & (
  { readonly start_line?: never } | { readonly start_line: number; readonly start_side: 'RIGHT' }
);

/** The body of `POST /repos/{owner}/{repo}/pulls/{number}/reviews`. */
export interface GithubReviewPayload {
  /** The head the comments' line numbers refer to. */
  readonly commit_id: string;
  readonly event: 'APPROVE' | 'REQUEST_CHANGES' | 'COMMENT';
  readonly body: string;
  readonly comments: readonly GithubReviewComment[];
}

/** A 1-based, inclusive span of head lines. */
export interface LineSpan {
  readonly start: number;
  readonly end: number;
}

export interface GithubReviewOptions {
  /**
   * Per path, the head-side spans of the pull request's diff hunks (`newStart` to
   * `newStart + newCount - 1`, against the PR's base, not an interdiff). GitHub rejects the whole
   * review when a comment falls outside them, so with this map such items go into the body.
   */
  readonly commentableRanges?: ReadonlyMap<string, readonly LineSpan[]>;
  /** The reviewer's own text for the top of the body; none by default (the reviewer writes it). */
  readonly summary?: string;
}

const events: Readonly<Record<UraVerdict, GithubReviewPayload['event']>> = {
  approve: 'APPROVE',
  'request-changes': 'REQUEST_CHANGES',
  comment: 'COMMENT',
};

const verdictLabels: Readonly<Record<UraVerdict, string>> = {
  approve: 'Approved',
  'request-changes': 'Changes requested',
  comment: 'Comments',
};

const outdatedLabels: Readonly<Record<OutdatedReason, string>> = {
  'lines-changed': 'outdated: the lines changed since',
  'file-deleted': 'outdated: the file was deleted after',
  'no-line-mapping': 'outdated: written against',
};

const shortSha = 12;

/**
 * The GitHub pull request review for an artifact. Line items become inline comments on the
 * head (`side: 'RIGHT'`); a note's one suggestion that replaces its anchored lines becomes a
 * ```` ```suggestion ```` block, any other suggestion a ```` ```diff ```` block of its derived
 * patch (until ADR 0162's placement of each suggestion on its own lands). Whole-file,
 * whole-change and outdated items, and lines outside `commentableRanges`, go into the body,
 * under the reviewer's summary when there is one. GitHub refuses a comment or a change request
 * that says nothing, so such a review's body falls back to the verdict's name. A note the agent
 * raised (a staged `/review` finding or a note a chat answer proposed) ends with a rule and
 * `_Generated by agent review. Confidence: 50%_`, without the confidence when it has none, even
 * after the reviewer edits it (ADR 0143). Pure: posting it is the caller's job.
 */
export function buildGithubReview(
  artifact: UraArtifact,
  options: GithubReviewOptions = {},
): GithubReviewPayload {
  const inline: GithubReviewComment[] = [];
  const general: string[] = [];
  for (const entry of artifact.entries) {
    const comment = commentFrom(entry, options.commentableRanges);
    if (comment === undefined) {
      general.push(generalSection(entry, options.commentableRanges));
    } else {
      inline.push(comment);
    }
  }
  const sections: string[] = [];
  const summary = options.summary?.trim() ?? '';
  if (summary !== '') {
    sections.push(summary);
  }
  if (general.length > 0) {
    sections.push('### Not attached to a line', ...general);
  }
  const verdict = artifact.verdict.value;
  if (verdict !== 'approve' && sections.length === 0 && inline.length === 0) {
    sections.push(verdictLabels[verdict]);
  }
  return {
    commit_id: artifact.summary.headSha,
    event: events[verdict],
    body: sections.join('\n\n'),
    comments: inline,
  };
}

function commentFrom(
  entry: UraEntry,
  ranges: GithubReviewOptions['commentableRanges'],
): GithubReviewComment | undefined {
  const { item, placement } = entry;
  if (placement.kind === 'outdated' || placement.anchor.kind !== 'lines') {
    return undefined;
  }
  const { path, startLine, endLine } = placement.anchor;
  if (!isCommentable(placement.anchor, ranges)) {
    return undefined;
  }
  const body = [headline(item, 'comment'), ...details(entry, true)].join('\n\n');
  if (startLine === endLine) {
    return { path, line: endLine, side: 'RIGHT', body };
  }
  return { path, start_line: startLine, start_side: 'RIGHT', line: endLine, side: 'RIGHT', body };
}

/**
 * The emoji and the Conventional Comments label with its decoration, then the title when there is
 * one: `🎉 **praise:** Nice.`, `⚠️ **issue (blocking):** Guard it.` (ADR 0131).
 */
function headline(item: UraItem, style: 'comment' | 'section'): string {
  let label: string = item.severity;
  if (item.blocking) {
    label += ' (blocking)';
  }
  const emoji = uraSeverityEmoji(item.severity);
  const title = escapeMarkdownHtml(item.title);
  if (style === 'section') {
    if (title === '') {
      return `#### ${emoji} ${label}`;
    }
    return `#### ${emoji} ${label}: ${title}`;
  }
  if (title === '') {
    return `${emoji} **${label}**`;
  }
  return `${emoji} **${label}:** ${title}`;
}

function isCommentable(
  { path, startLine, endLine }: Extract<UraAnchor, { kind: 'lines' }>,
  ranges: GithubReviewOptions['commentableRanges'],
): boolean {
  return (
    ranges === undefined ||
    (ranges.get(path) ?? []).some((range) => range.start <= startLine && endLine <= range.end)
  );
}

function generalSection(entry: UraEntry, ranges: GithubReviewOptions['commentableRanges']): string {
  const { item, placement } = entry;
  return [
    headline(item, 'section'),
    location(item, placement, ranges),
    ...details(entry, false),
  ].join('\n\n');
}

function location(
  item: UraItem,
  placement: UraEntry['placement'],
  ranges: GithubReviewOptions['commentableRanges'],
): string {
  if (placement.kind === 'outdated') {
    const label = outdatedLabels[placement.reason];
    return `\`${formatUraAnchor(item.anchor)}\` (${label} ${item.headSha.slice(0, shortSha)})`;
  }
  const { anchor } = placement;
  switch (anchor.kind) {
    case 'change': {
      return 'On the whole change.';
    }
    case 'file': {
      return `On \`${revealFormatControls(anchor.path)}\`.`;
    }
    case 'lines': {
      let outside = '';
      if (ranges !== undefined) {
        outside = " (outside the pull request's diff)";
      }
      return `On \`${formatUraAnchor(anchor)}\`${outside}.`;
    }
  }
}

function details(entry: UraEntry, isInline: boolean): string[] {
  const { item } = entry;
  const parts: string[] = [];
  const body = item.body.trim();
  if (body !== '') {
    parts.push(body);
  }
  parts.push(...suggestionBlocks(entry, isInline));
  if (item.origin.kind === 'chat-answer') {
    parts.push('---', agentFooter(item.origin));
  }
  return parts;
}

function suggestionBlocks(entry: UraEntry, isInline: boolean): string[] {
  if (isInline) {
    const replacement = replacementLines(entry);
    if (replacement !== undefined) {
      return [fenceCodeBlock({ info: 'suggestion', content: replacement.join('\n') })];
    }
  }
  return entry.suggestions.map((placed) => diffBlock(placed));
}

/** A suggestion's derived patch, or its replacement when there is none to show. */
function diffBlock({ suggestion, patch }: UraPlacedSuggestion): string {
  if (patch !== undefined) {
    return fenceCodeBlock({ info: 'diff', content: patch });
  }
  const { path, startLine, endLine } = suggestion;
  const lines = formatUraAnchor({ kind: 'lines', path, startLine, endLine });
  return `Replace \`${lines}\` with:\n\n${fenceCodeBlock({ info: '', content: suggestion.replacement })}`;
}

/**
 * The new text of the anchored lines, when the note has one suggestion, current on the head, that
 * either replaces exactly those lines or whose patch is one hunk whose changes stay inside the
 * anchor and which shows every anchored line, so the lines can be replaced wholesale.
 */
function replacementLines({ item, suggestions }: UraEntry): string[] | undefined {
  const { anchor } = item;
  const [only, ...others] = suggestions;
  if (
    only === undefined ||
    others.length > 0 ||
    only.placement.kind !== 'current' ||
    anchor.kind !== 'lines' ||
    only.suggestion.path !== anchor.path
  ) {
    return undefined;
  }
  const { suggestion } = only;
  if (suggestion.startLine === anchor.startLine && suggestion.endLine === anchor.endLine) {
    if (suggestion.replacement === '') {
      return [];
    }
    return suggestion.replacement.split('\n');
  }
  if (only.patch === undefined) {
    return undefined;
  }
  const parsed = parseSuggestedPatch(only.patch, anchor);
  if (!parsed.ok) {
    return undefined;
  }
  const [hunk, ...rest] = parsed.value.hunks;
  if (hunk === undefined || rest.length > 0 || !isCovering(hunk, anchor)) {
    return undefined;
  }
  return anchoredLines(hunk, anchor);
}

/** The new side of a hunk's anchored lines, with insertions directly before or after them. */
function anchoredLines(hunk: PatchHunk, anchor: Extract<UraAnchor, { kind: 'lines' }>): string[] {
  const { startLine, endLine } = anchor;
  const lines: string[] = [];
  let nextOld = hunk.oldStart;
  for (const line of hunk.lines) {
    if (line.kind === 'added') {
      // Insertions directly before or after the anchored lines belong to the replacement.
      if (nextOld >= startLine && nextOld <= endLine + 1) {
        lines.push(line.content);
      }
      continue;
    }
    if (line.kind === 'context' && nextOld >= startLine && nextOld <= endLine) {
      lines.push(line.content);
    }
    nextOld += 1;
  }
  return lines;
}

function isCovering(
  hunk: Pick<PatchHunk, 'oldStart' | 'oldCount'>,
  anchor: Extract<UraAnchor, { kind: 'lines' }>,
): boolean {
  return (
    hunk.oldCount > 0 &&
    hunk.oldStart <= anchor.startLine &&
    hunk.oldStart + hunk.oldCount - 1 >= anchor.endLine
  );
}

/** Says the agent raised the note, and how sure it was when the note is a finding that says. */
function agentFooter({ confidence }: Extract<UraOrigin, { kind: 'chat-answer' }>): string {
  if (confidence === undefined) {
    return '_Generated by agent review._';
  }
  return `_Generated by agent review. Confidence: ${String(Math.round(confidence * 100))}%_`;
}
